using System.Numerics;
using System.Text;
namespace TrsRisc.Tools;

/// <summary>Reproducible binary64 EXP coefficients and independent reference vectors.
/// All reference arithmetic is integer fixed point with 400 decimal places;
/// neither Math.Exp nor the interpreter under test supplies expected outputs.</summary>
public static class ExpAccuracy
{
    private static readonly BigInteger Unit = BigInteger.Pow(10, 400);

    // Round a positive rational to nearest, ties to even, exactly once.
    private static BigInteger Round(BigInteger numerator, BigInteger denominator)
    {
        BigInteger quotient = BigInteger.DivRem(numerator, denominator, out var remainder);
        int comparison = (remainder * 2).CompareTo(denominator);
        return comparison > 0 || comparison == 0 && !quotient.IsEven ? quotient + 1 : quotient;
    }
    private static ulong Binary64(BigInteger numerator, BigInteger denominator)
    {
        if (numerator.IsZero) return 0;
        int exponent = (int)(numerator.GetBitLength() - denominator.GetBitLength());
        if (exponent >= 0 ? numerator < (denominator << exponent) : (numerator << -exponent) < denominator) exponent--;
        if (exponent < -1022) return (ulong)Round(numerator << 1074, denominator);
        if (exponent > 1023) return 0x7ff0000000000000;
        int shift = 52 - exponent;
        var significand = shift >= 0 ? Round(numerator << shift, denominator) : Round(numerator, denominator << -shift);
        if (significand == BigInteger.One << 53) { significand >>= 1; exponent++; }
        if (exponent > 1023) return 0x7ff0000000000000;
        return ((ulong)(exponent + 1023) << 52) | ((ulong)significand & 0xfffffffffffff);
    }
    private static BigInteger Fixed(double value)
    {
        ulong bits = BitConverter.DoubleToUInt64Bits(value);
        int exponent = (int)((bits >> 52) & 2047);
        BigInteger mantissa = bits & 0xfffffffffffff;
        if (exponent != 0) mantissa |= BigInteger.One << 52;
        int shift = exponent == 0 ? -1074 : exponent - 1075;
        BigInteger magnitude = shift >= 0 ? (mantissa * Unit) << shift : (mantissa * Unit) >> -shift;
        return (bits >> 63) != 0 ? -magnitude : magnitude;
    }
    private static ulong Reference(double value)
    {
        // |value/1024| < 1. Taylor converges quickly at 400 decimal places.
        // Ten squarings restore exp(value). Fixed-point truncation error is
        // negligible compared with a binary64 ULP even at exp(-746).
        BigInteger reduced = Fixed(value) / 1024, sum = Unit, term = Unit;
        for (int j = 1; ; j++)
        {
            term = term * reduced / (Unit * j);
            if (term.IsZero) break;
            sum += term;
        }
        for (int j = 0; j < 10; j++) sum = sum * sum / Unit;
        return Binary64(sum, Unit);
    }
    public static void Generate(string coefficientPath, string vectorPath)
    {
        var coefficients = new StringBuilder("/* Generated by exp-accuracy; exact-rounded (-1)^j/j!, highest degree first. */\nstatic const double n32_exp_coefficients[]={\n");
        BigInteger factorial = BigInteger.One;
        var entries = new string[18];
        for (int j = 0; j <= 17; j++)
        {
            if (j > 0) factorial *= j;
            ulong bits = Binary64(BigInteger.One, factorial);
            int exponent = (int)((bits >> 52) & 2047) - 1023;
            entries[j] = $" {(j % 2 == 0 ? "" : "-")}0x1.{bits & 0xfffffffffffff:x13}p{exponent:+0;-0;+0}";
        }
        coefficients.AppendJoin(",\n", entries.Reverse()).Append("\n};\n");
        File.WriteAllText(coefficientPath, coefficients.ToString());
        var inputs = new SortedSet<double> { 0, double.Epsilon, -double.Epsilon, 1, -1, 700, -700, -746, 710 };
        for (int j = 0; j <= 4096; j++) inputs.Add(-746 + j * (1456.0 / 4096));
        // Dense ULP neighborhoods around reduction boundaries and overflow /
        // normal-subnormal / half-minimum-subnormal transitions.
        foreach (double boundary in new[] { 709.782712893384, -708.3964185322641, -744.4400719213812, -745.1332191019411 })
        {
            double below = boundary, above = boundary;
            for (int j = 0; j < 32; j++) { inputs.Add(below); inputs.Add(above); below = Math.BitDecrement(below); above = Math.BitIncrement(above); }
        }
        for (int j = -1074; j <= 1023; j += 17)
        {
            double boundary = j * 0.6931471805599453;
            inputs.Add(Math.BitDecrement(boundary)); inputs.Add(boundary); inputs.Add(Math.BitIncrement(boundary));
        }
        var vectors = new StringBuilder("/* Generated by exp-accuracy using 400-decimal-place BigInteger arithmetic. */\nstatic const struct {uint64_t input,expected;} exp_vectors[]={\n");
        foreach (double value in inputs) vectors.Append($" {{UINT64_C(0x{BitConverter.DoubleToUInt64Bits(value):x16}),UINT64_C(0x{Reference(value):x16})}},\n");
        vectors.Append("};\n");File.WriteAllText(vectorPath, vectors.ToString());
        Console.WriteLine($"Generated 18 coefficients and {inputs.Count} high-precision EXP vectors");
    }
}
